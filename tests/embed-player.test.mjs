assert.match(page,/meta name="referrer" content="strict-origin-when-cross-origin"/);
assert.match(qa,/sNnJ5dzHe3I/);
assert.equal(data.articles[0].youtubeVideoUrl,'https://www.youtube.com/watch?v=sNnJ5dzHe3I');
