import assert from 'node:assert/strict';
import fs from 'node:fs';
import {makeSitemap,makeArchive,enhanceArticleHtml,articlePath} from '../functions/_shared/seo.js';
import {onRequestGet as siteMapRequest} from '../functions/sitemap.xml.js';
import {onRequestGet as robotsRequest} from '../functions/robots.txt.js';
import {onRequestGet as archiveRequest} from '../functions/archive.js';
import {onRequestGet as feedRequest} from '../functions/feed.xml.js';
import {onRequestGet as articleRequest} from '../functions/articles/[[path]].js';
import {onRequestGet as indexRequest} from '../functions/index.js';
const manifest=JSON.parse(fs.readFileSync(new URL('../public/data/articles.json',import.meta.url),'utf-8'));
const original=fs.readFileSync(new URL('../public/articles/2026/10/youtube_comment_topics_web_2026-10-10_12-50-29-330.html',import.meta.url),'utf-8');
const url='https://www.cometopi-example.test/articles/2026/10/youtube_comment_topics_web_2026-10-10_12-50-29-330.html';
const item=manifest.articles[0];
assert(articlePath(item.path));
assert(!articlePath('/articles/../../secret.html'));
const changed=enhanceArticleHtml(original,url,item);
assert(changed.includes('<link rel="canonical" href="'+url+'">'));
assert(changed.includes('application/ld+json'));
assert(changed.includes('name="description"'));
assert(changed.includes('<meta property="og:title"'));
assert(changed.endsWith(original.slice(original.lastIndexOf('</head>')+7)), 'article body untouched');
assert.equal(fs.readFileSync(new URL('../public/articles/2026/10/youtube_comment_topics_web_2026-10-10_12-50-29-330.html',import.meta.url),'utf-8'),original,'original HTML never overwritten');
const canonicalDomain=enhanceArticleHtml(original,url,item,'https://cometopi7.example.jp');assert(canonicalDomain.includes('href="https://cometopi7.example.jp/articles/'));
const sitemap=makeSitemap('https://www.cometopi-example.test',manifest);
assert(sitemap.includes('<loc>'+url+'</loc>'));
assert(sitemap.includes('<loc>https://www.cometopi-example.test/archive</loc>'));
const archived=makeArchive('https://www.cometopi-example.test',manifest,1);
assert(archived.includes('href="'+item.path+'"'));
assert(archived.includes(item.title));
const hidden={articles:[...manifest.articles,{...item,path:'/articles/2026/10/hidden.html',visible:false}]};
assert(!makeSitemap('https://www.cometopi-example.test',hidden).includes('/hidden.html'));
assert(!makeArchive('https://www.cometopi-example.test',hidden).includes('/hidden.html'));
const root='https://www.cometopi-example.test';
const indexHtml=fs.readFileSync(new URL('../public/index.html',import.meta.url),'utf-8');
const env={ASSETS:{fetch:async()=>new Response(JSON.stringify(manifest),{status:200,headers:{'Content-Type':'application/json'}})}};
let res=await siteMapRequest({request:new Request(root+'/sitemap.xml'),env});
assert.equal(res.status,200);assert((await res.text()).includes(url));
res=await robotsRequest({request:new Request(root+'/robots.txt'),env});
assert((await res.text()).includes('Sitemap: '+root+'/sitemap.xml'));
res=await archiveRequest({request:new Request(root+'/archive'),env});
assert((await res.text()).includes('href="'+item.path+'"'));
res=await feedRequest({request:new Request(root+'/feed.xml'),env});
assert((await res.text()).includes('<rss version="2.0">'));
res=await articleRequest({request:new Request(url),env,next:async()=>new Response(original,{status:200,headers:{'Content-Type':'text/html; charset=utf-8'}})});
assert.equal(res.status,200);assert((await res.text()).includes('<link rel="canonical"'));
const home=await indexRequest({request:new Request(root+'/'),env:{...env,ASSETS:{fetch:async()=>new Response(indexHtml,{headers:{'Content-Type':'text/html; charset=utf-8'}})}}});
const homeText=await home.text();assert(homeText.includes('<link rel="canonical" href="'+root+'/"'));assert(homeText.includes('application/ld+json'));assert(homeText.includes('/archive')); 
console.log('PASS: SEO サイトマップ / robots / アーカイブ / RSS / JSON-LD / canonical / 原本HTML不変');
